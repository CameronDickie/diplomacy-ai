package main

import (
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/zond/godip"
	"github.com/zond/godip/variants/classical"
)

type adjacency struct {
	army         []string
	fleet        []string
	fleetByCoast map[string][]string
}

func main() {
	outputPath := flag.String("out", "", "TypeScript file to write")
	flag.Parse()
	if *outputPath == "" {
		fmt.Fprintln(os.Stderr, "-out is required")
		os.Exit(2)
	}

	content, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(*outputPath, []byte(content), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() (string, error) {
	state, err := classical.Start()
	if err != nil {
		return "", err
	}
	graph := state.Graph()
	entries := make(map[string]adjacency)

	for _, province := range graph.Provinces() {
		super := province.Super()
		internal := fromGodipProvince(super)
		entry := entries[internal]
		entry.army = destinations(graph, super, godip.Land)

		coasts := graph.Coasts(super)
		if len(coasts) > 1 {
			entry.fleetByCoast = make(map[string][]string)
			for _, coast := range coasts {
				if coast == super || !graph.Flags(coast)[godip.Sea] {
					continue
				}
				entry.fleetByCoast[fromGodipCoast(coast.Sub())] =
					destinations(graph, coast, godip.Sea)
			}
		} else {
			entry.fleet = destinations(graph, super, godip.Sea)
		}
		entries[internal] = entry
	}

	ids := make([]string, 0, len(entries))
	for id := range entries {
		ids = append(ids, id)
	}
	sort.Strings(ids)

	var output strings.Builder
	output.WriteString("// Code generated by engine/cmd/generate-board; DO NOT EDIT.\n")
	output.WriteString("import type { Coast, TerritoryId } from '../types/territory.js';\n\n")
	output.WriteString("export interface AdjacencyEntry {\n")
	output.WriteString("  army: TerritoryId[];\n")
	output.WriteString("  fleet: TerritoryId[] | Partial<Record<Coast, TerritoryId[]>>;\n")
	output.WriteString("}\n\n")
	output.WriteString("export const ADJACENCY: Record<TerritoryId, AdjacencyEntry> = {\n")
	for _, id := range ids {
		entry := entries[id]
		fmt.Fprintf(&output, "  %s: { army: %s, fleet: ", id, tsArray(entry.army))
		if entry.fleetByCoast == nil {
			output.WriteString(tsArray(entry.fleet))
		} else {
			output.WriteString("{ ")
			coastNames := make([]string, 0, len(entry.fleetByCoast))
			for coast := range entry.fleetByCoast {
				coastNames = append(coastNames, coast)
			}
			sort.Strings(coastNames)
			for index, coast := range coastNames {
				if index > 0 {
					output.WriteString(", ")
				}
				fmt.Fprintf(&output, "%s: %s", coast, tsArray(entry.fleetByCoast[coast]))
			}
			output.WriteString(" }")
		}
		output.WriteString(" },\n")
	}
	output.WriteString("};\n")
	return output.String(), nil
}

func destinations(graph godip.Graph, source godip.Province, flag godip.Flag) []string {
	seen := make(map[string]bool)
	var result []string
	for destination, edgeFlags := range graph.Edges(source, false) {
		if !edgeFlags[flag] || !graph.Flags(destination)[flag] {
			continue
		}
		internal := fromGodipProvince(destination)
		if !seen[internal] {
			seen[internal] = true
			result = append(result, internal)
		}
	}
	sort.Strings(result)
	return result
}

func tsArray(values []string) string {
	quoted := make([]string, len(values))
	for index, value := range values {
		quoted[index] = fmt.Sprintf("'%s'", value)
	}
	return "[" + strings.Join(quoted, ", ") + "]"
}

func fromGodipProvince(province godip.Province) string {
	aliases := map[string]string{
		"mid": "MAO",
		"nat": "NAO",
		"nrg": "NWG",
		"nwy": "NOR",
	}
	super := province.Super()
	if alias, ok := aliases[string(super)]; ok {
		return alias
	}
	return strings.ToUpper(string(super))
}

func fromGodipCoast(coast godip.Province) string {
	return map[string]string{
		"nc": "NORTH",
		"sc": "SOUTH",
		"ec": "EAST",
		"wc": "WEST",
	}[string(coast)]
}
