import { randomUUID } from 'crypto';
import type {
  Order,
  Power,
  RetreatDestination,
  SubmitBuildsPayload,
} from '@diplomacy/shared';
import type {
  ControllerContext,
  ControllerDecision,
  DiplomaticInitiativeDecision,
  DiplomaticReplyDecision,
  PowerController,
} from './PowerController.js';

export class StubLlmController implements PowerController {
  constructor(readonly power: Power) {}

  async requestDiplomaticInitiative(
    context: ControllerContext
  ): Promise<DiplomaticInitiativeDecision> {
    return {
      toPower: null,
      message: '',
      strategicSummary: context.memory.strategicSummary,
      agreements: context.memory.agreements,
    };
  }

  async requestDiplomaticReply(): Promise<DiplomaticReplyDecision> {
    return {
      reply: 'Message received. I will consider this in my next phase decision.',
      expectsReply: false,
      strategicSummary: 'No strategic plan has been generated by the stub controller.',
      agreements: [],
    };
  }

  async requestOrders(
    context: ControllerContext
  ): Promise<ControllerDecision<Order[]>> {
    return {
      actions: context.state.units
        .filter(unit => unit.power === this.power && !unit.mustRetreat)
        .map(unit => ({
          id: randomUUID(),
          power: this.power,
          unitTerritory: unit.territory,
          unitCoast: unit.coast,
          type: 'HOLD' as const,
          targetTerritory: null,
          targetCoast: null,
          supportedUnit: null,
          supportedDestination: null,
        })),
      strategicSummary: 'Stub fallback: hold all units.',
      agreements: context.memory.agreements,
    };
  }

  async requestRetreats(
    context: ControllerContext
  ): Promise<ControllerDecision<Record<string, RetreatDestination | null>>> {
    return {
      actions: Object.fromEntries(
        context.state.units
          .filter(unit => unit.power === this.power && unit.mustRetreat)
          .map(unit => [unit.id, null])
      ),
      strategicSummary: 'Stub fallback: disband all dislodged units.',
      agreements: context.memory.agreements,
    };
  }

  async requestBuilds(
    context: ControllerContext
  ): Promise<ControllerDecision<Omit<SubmitBuildsPayload, 'gameId'>>> {
    const ownedCenters = Object.values(context.state.territories).filter(
      territory => territory.owner === this.power && territory.isSupplyCenter
    ).length;
    const units = context.state.units.filter(unit => unit.power === this.power);
    const disbandCount = Math.max(0, units.length - ownedCenters);
    return {
      actions: {
        builds: [],
        disbands: units.slice(0, disbandCount).map(unit => unit.id),
      },
      strategicSummary: 'Stub fallback: waive builds and disband deterministically.',
      agreements: context.memory.agreements,
    };
  }
}
